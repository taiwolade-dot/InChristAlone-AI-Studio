from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
from reportlab.lib.styles import getSampleStyleSheet


def generate_pdf_title():

    return "AI Ministry Intelligence Leadership Report"


def build_pdf_content(document):

    styles = getSampleStyleSheet()

    content = []

    content.append(
        Paragraph(
            generate_pdf_title(),
            styles["Title"]
        )
    )

    content.append(
        Spacer(1, 12)
    )

    metadata = document.get(
        "metadata",
        {}
    )

    content.append(
        Paragraph(
            f"Generated By: {metadata.get('generated_by', '')}",
            styles["Normal"]
        )
    )

    content.append(
        Paragraph(
            f"Generated On: {metadata.get('generated_on', '')}",
            styles["Normal"]
        )
    )

    content.append(
        Spacer(1, 12)
    )

    overview = document.get(
        "sections",
        {}
    ).get(
        "overview",
        {}
    )

    content.append(
        Paragraph(
            "Ministry Overview",
            styles["Heading2"]
        )
    )

    for key, value in overview.items():

        content.append(
            Paragraph(
                f"{key.title()}: {value}",
                styles["Normal"]
            )
        )

    return content


def generate_pdf_report(document, filename):

    pdf = SimpleDocTemplate(
        filename
    )

    content = build_pdf_content(
        document
    )

    pdf.build(
        content
    )

    return filename
